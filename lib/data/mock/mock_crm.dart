/// Midnight-aligned date `days` from today (negative = past).
DateTime day(int days, [int hour = 10, int minute = 0]) {
  final n = DateTime.now();
  return DateTime(n.year, n.month, n.day + days, hour, minute);
}

Note _note(String id, String text, int daysAgo) => Note(id: id, text: text, at: day(-daysAgo, 15));

ActivityEntry _act(String id, String title, int daysAgo, ActivityKind kind, [String? detail]) =>
    ActivityEntry(id: id, title: title, detail: detail, at: day(-daysAgo, 11), kind: kind);

